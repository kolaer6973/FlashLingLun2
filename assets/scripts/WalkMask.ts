/** 判断某点能不能站（参数为地图局部坐标，原点在屏幕中心） */
export function isWalkable(x: number, y: number): boolean {
    const col = Math.floor((x + 960) / CELL_SIZE);
    const row = Math.floor((540 - y) / CELL_SIZE);
    if (col < 0 || col >= GRID_COLS || row < 0 || row >= GRID_ROWS) return false;
    return WALK_ROWS[row].charAt(col) === '.';
}
